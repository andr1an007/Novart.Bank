function setLanguage(language) {
  const dictionary = translations[language];

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;

    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;

    if (dictionary[key]) {
      element.placeholder = dictionary[key];
    }
  });

  document.documentElement.lang = language;
  localStorage.setItem("siteLanguage", language);
}


function updateNewCardNamePlaceholder() {
  const newCardName = document.getElementById("newCardName");

  if (!newCardName) return;

  const language = localStorage.getItem("siteLanguage") || "English";

  newCardName.placeholder =
    language === "Українська" || language === "uk"
      ? "напр. Щоденні витрати"
      : "e.g. Daily expenses";
}
